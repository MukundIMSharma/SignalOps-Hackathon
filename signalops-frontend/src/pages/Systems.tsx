import { useFetch } from '../api'
import { Badge, Card, ErrorNote, Loading, Mono, time } from '../components/ui'
import type { SystemInfo } from '../types'

export default function Systems() {
  const { data, error, loading, reload } = useFetch<SystemInfo[]>('/api/systems')
  return (
    <div className="space-y-4">
      <div className="flex items-end justify-between">
        <div>
          <h1 className="text-xl font-semibold text-zinc-50">Systems / MCP</h1>
          <p className="text-sm text-zinc-500">Two independent business systems, each exposed as an MCP server generated by Synapse Auto.</p>
        </div>
        <button onClick={reload} disabled={loading} className="rounded border border-zinc-700 px-3 py-1.5 text-sm text-zinc-300 hover:bg-zinc-800 disabled:opacity-50">
          {loading ? 'Checking…' : 'Refresh tools'}
        </button>
      </div>
      {error && <ErrorNote>{error}</ErrorNote>}
      {loading && !data && <Loading what="systems (starting MCP sessions)" />}
      <div className="grid gap-4 lg:grid-cols-2">
        {data?.map(s => (
          <Card key={s.name} title={<span className="normal-case">{s.repo}</span>}
            actions={s.mcp.connected ? <Badge t="green" icon="●">MCP connected</Badge> : <Badge t="red" icon="✕">MCP disconnected</Badge>}>
            <dl className="grid grid-cols-2 gap-y-2 text-sm">
              <dt className="text-zinc-500">API health</dt>
              <dd>{s.api.healthy ? <Badge t="green" icon="✓">healthy</Badge> : <Badge t="red" icon="✕">down</Badge>} <Mono>{s.base_url}</Mono></dd>
              <dt className="text-zinc-500">API endpoints (OpenAPI)</dt><dd className="tabular-nums">{s.api.endpoint_count ?? '—'}</dd>
              <dt className="text-zinc-500">MCP tools</dt><dd className="tabular-nums">{s.mcp.tool_count}{s.mcp.connect_ms != null && <span className="text-xs text-zinc-500"> · session {s.mcp.connect_ms}ms</span>}</dd>
              <dt className="text-zinc-500">Synapse server</dt><dd><Mono>{s.server_id.slice(0, 8)}…</Mono></dd>
              <dt className="text-zinc-500">Last discovery</dt><dd><Mono>{time(s.last_discovery)} UTC</Mono></dd>
            </dl>
            {s.api.error && <p className="mt-2 text-xs text-red-300">API: {s.api.error}</p>}
            {s.mcp.error && <p className="mt-2 text-xs text-red-300">MCP: {s.mcp.error}</p>}
            <ul className="mt-4 space-y-1.5 border-t border-zinc-800 pt-3">
              {s.mcp.tools.map(t => (
                <li key={t.name} className={`rounded px-2 py-1 ${t.new ? 'bg-emerald-500/10 ring-1 ring-emerald-500/40' : ''}`}>
                  <div className="flex items-center gap-2">
                    <span className="font-mono text-[13px] text-zinc-100">{t.name}</span>
                    {t.params.length > 0 && <span className="font-mono text-[11px] text-zinc-500">({t.params.join(', ')})</span>}
                    {t.new && <Badge t="green" icon="★">newly discovered</Badge>}
                  </div>
                  <div className="text-xs text-zinc-500">{t.description}</div>
                </li>
              ))}
            </ul>
          </Card>
        ))}
      </div>
    </div>
  )
}
